function initLiveSearch() {
    const searchInput = document.getElementById("tableSearch");
    if (!searchInput) return;

    searchInput.addEventListener("keyup", () => {
        const keyword = searchInput.value.toLowerCase().trim();
        const rows = document.querySelectorAll("table tbody tr");

        rows.forEach((row) => {
            if (row.cells.length < 3) return;
            const matkul = row.cells[1].textContent.toLowerCase();
            const dosen = row.cells[2].textContent.toLowerCase();
            const ruang = row.cells[3].textContent.toLowerCase();

            if (
                matkul.includes(keyword) ||
                dosen.includes(keyword) ||
                ruang.includes(keyword)
            ) {
                row.style.display = "";
            } else {
                row.style.display = "none";
            }
        });
    });
}

