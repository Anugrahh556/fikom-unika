// =========================================================================
function generateDynamicCalendar() {
    const waktuSistem = new Date();
    const tahunAktif = waktuSistem.getFullYear();
    const bulanAktif = waktuSistem.getMonth();
    const tanggalHariIni = waktuSistem.getDate();

    const namaBulanIndo = [
        "Januari",
        "Februari",
        "Maret",
        "April",
        "Mei",
        "Juni",
        "Juli",
        "Agustus",
        "September",
        "Oktober",
        "November",
        "Desember",
    ];

    const headerBulan = document.querySelector(".calendar-header h2");
    if (headerBulan) {
        headerBulan.textContent = `${namaBulanIndo[bulanAktif]} ${tahunAktif}`;
    }

    const calendarDatesContainer = document.getElementById(
        "calendarDatesContainer",
    );
    if (!calendarDatesContainer) return;
    calendarDatesContainer.innerHTML = "";

    const hariPertamaBulan = new Date(tahunAktif, bulanAktif, 1).getDay();
    const jumlahHariBulanIni = new Date(
        tahunAktif,
        bulanAktif + 1,
        0,
    ).getDate();
    const jumlahHariBulanLalu = new Date(tahunAktif, bulanAktif, 0).getDate();

    for (let i = hariPertamaBulan; i > 0; i--) {
        const dayElement = document.createElement("div");
        dayElement.className = "mute";
        dayElement.style.cssText =
            "padding: 8px; text-align: center; font-size: 13px; font-family: 'Poppins'; color: #98a2b3; opacity: 0.5;";
        dayElement.textContent = jumlahHariBulanLalu - i + 1;
        calendarDatesContainer.appendChild(dayElement);
    }

    for (let tanggal = 1; tanggal <= jumlahHariBulanIni; tanggal++) {
        const dayElement = document.createElement("div");
        dayElement.style.cssText =
            "padding: 8px; text-align: center; font-size: 13px; font-family: 'Poppins'; color: #344054; position: relative; cursor: pointer; display: flex; align-items: center; justify-content: center; margin: auto; width: 32px; height: 32px;";
        dayElement.textContent = tanggal;

        if (tanggal === tanggalHariIni) {
            dayElement.classList.add("active");
            dayElement.style.backgroundColor = "#9a1c1c";
            dayElement.style.color = "#ffffff";
            dayElement.style.borderRadius = "50%";
            dayElement.style.fontWeight = "600";
        }
        calendarDatesContainer.appendChild(dayElement);
    }

    const totalSlotTerisi = hariPertamaBulan + jumlahHariBulanIni;
    const sisaSlotKosong = 42 - totalSlotTerisi;

    for (
        let tanggalBerikutnya = 1;
        tanggalBerikutnya <= sisaSlotKosong;
        tanggalBerikutnya++
    ) {
        const dayElement = document.createElement("div");
        dayElement.className = "mute";
        dayElement.style.cssText =
            "padding: 8px; text-align: center; font-size: 13px; font-family: 'Poppins'; color: #98a2b3; opacity: 0.5;";
        dayElement.textContent = tanggalBerikutnya;
        calendarDatesContainer.appendChild(dayElement);
    }
}
