// 9. SMART STATISTIC ENGINE: MENGHITUNG DATA BERDASARKAN HARI INI
// =========================================================================
function updateDashboardStats() {
    const elDosen = document.getElementById("statTotalDosen");
    const elMatkul = document.getElementById("statTotalMatkul");
    const elRuangan = document.getElementById("statTotalRuangan");

    const allJadwal = Object.values(masterJadwalFikom).flat();
    const validClasses = allJadwal.filter((j) => j.matkul && j.matkul !== "-");

    // 1. Statistik Dosen: Dihitung dari jadwal, menormalkan penulisan singkatan agar tidak ganda (Target: 26)
    const uniqueDosen = new Set(
        validClasses
            .map((j) => {
                let dName = j.dosen;
                // Normalisasi nama dosen yang disingkat di database
                if (dName.includes("Anirma K. Ginting"))
                    return "Anirma Kandida Ginting, S.Kom., M.Kom";
                if (dName.includes("Dr. P.B.N. Simangunsong"))
                    return "Dr. Pandi Barita Nauli Simangunsong, S.Kom, M.Kom";
                return dName.trim();
            })
            .filter(
                (dosen) => dosen && dosen !== "-" && dosen !== "Dosen Pengampu",
            ),
    );

    // 3. Statistik Matakuliah: Menghitung kelas/section unik untuk mengabaikan duplikasi jadwal gabungan (Target: 212)
    const uniqueMatkul = new Set(
        validClasses.map((j) => `${j.matkul.trim()} - ${j.kelas.trim()}`),
    );

    // 2. Statistik Ruangan: Normalisasi variasi penulisan Lab agar tidak duplicate (Lab. A == Lab-A)
    const normalizedRuangan = new Set(
        validClasses.map((j) => {
            // Mengubah "Lab-A", "Lab A", "Lab.A" menjadi "Lab. A"
            return j.ruang.replace(/Lab[\s\-\.]*([A-Z])/i, "Lab. $1").trim();
        }),
    );

    if (elDosen) elDosen.innerText = uniqueDosen.size;
    if (elMatkul) elMatkul.innerText = uniqueMatkul.size;
    if (elRuangan) elRuangan.innerText = normalizedRuangan.size;
}
