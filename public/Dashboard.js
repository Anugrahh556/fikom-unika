// =========================================================================
// 3. F-01: LOGIKA UTAMA RENDER TABEL & WIDGET RUANGAN TERPAKAI
// =========================================================================
function renderDashboardData(namaHari) {
    const tableBody = document.querySelector("table tbody");
    const ruangContainer =
        document.querySelector(".ruangan-terpakai-container") ||
        document.getElementById("ruanganTerpakaiList");

    if (!tableBody) return;
    tableBody.innerHTML = "";

    // Panggil update statistik cerdas global
    updateDashboardStats();

    let jadwalHariIni = masterJadwalFikom[namaHari] || [];

    // --- SMART FILTERING LOGIC (DATA SEPARATION & PRIORITY) ---
    const currentTime = new Date();
    const strCurrentTime =
        String(currentTime.getHours()).padStart(2, "0") +
        "." +
        String(currentTime.getMinutes()).padStart(2, "0");

    let aktifList = [];
    let selesaiList = [];

    jadwalHariIni.forEach((item) => {
        // Auto-Pagination & Sorting: Filter pemisah jadwal selesai dan berjalan secara presisi
        const jamParts = item.jam.includes(" - ")
            ? item.jam.split(" - ")
            : item.jam.split("-");
        const jamSelesai = jamParts[1]?.trim().replace(":", ".");
        if (strCurrentTime > jamSelesai) {
            selesaiList.push(item);
        } else {
            aktifList.push(item);
        }
    });

    // Sort jadwal aktif berdasarkan jam agar prioritas Berjalan/Akan Datang selalu di atas
    aktifList.sort((a, b) => a.jam.localeCompare(b.jam));
    selesaiList.sort((a, b) => a.jam.localeCompare(b.jam));

    // Injeksi Elemen UI Indikator & Toggle Button di atas tabel
    let filterControl = document.getElementById("smartFilterIndicator");
    if (!filterControl) {
        filterControl = document.createElement("div");
        filterControl.id = "smartFilterIndicator";
        filterControl.style.cssText =
            "display: flex; justify-content: space-between; align-items: center; margin-bottom: 16px; padding: 12px 16px; background: #f0fdf4; border-radius: 8px; border: 1px solid #bbf7d0;";

        const insertionPoint =
            document.querySelector(".table-responsive") ||
            document.querySelector("table");
        if (insertionPoint && insertionPoint.parentNode) {
            insertionPoint.parentNode.insertBefore(
                filterControl,
                insertionPoint,
            );
        }
    }

    // Gabungkan list jadwal dengan memprioritaskan jadwal aktif di urutan teratas
    let jadwalRender = window.tampilkanSemuaJadwal
        ? [...aktifList, ...selesaiList]
        : [...aktifList];

    if (filterControl) {
        filterControl.innerHTML = `
            <span style="font-size: 13px; color: #15803d; font-weight: 500; font-family: 'Poppins';">
                <i class="fa-solid fa-circle-check" style="margin-right: 6px;"></i>
                Menampilkan <strong>${aktifList.length}</strong> jadwal aktif saat ini.
            </span>
            <button onclick="filterJadwal('${namaHari}')" style="background: white; border: 1px solid #bbf7d0; color: #15803d; padding: 6px 12px; border-radius: 6px; font-size: 12px; font-weight: 600; cursor: pointer; transition: 0.2s; box-shadow: 0 1px 2px rgba(0,0,0,0.05);">
                ${window.tampilkanSemuaJadwal ? '<i class="fa-solid fa-eye-slash"></i> Sembunyikan Jadwal Selesai' : '<i class="fa-solid fa-eye"></i> Lihat Semua Jadwal'}
            </button>
        `;
        // Sembunyikan banner filter jika hari sedang libur atau jadwal total kosong
        filterControl.style.display =
            namaHari === "Sabtu" ||
            namaHari === "Minggu" ||
            jadwalHariIni.length === 0
                ? "none"
                : "flex";
    }

    // SINKRONISASI HARI LIBUR SABTU / MINGGU ATAU DATA JADWAL SELESAI
    if (
        namaHari === "Sabtu" ||
        namaHari === "Minggu" ||
        jadwalHariIni.length === 0
    ) {
        tableBody.innerHTML = `<tr><td colspan="7" style="text-align: center; padding: 35px; color: #667085; font-family: 'Poppins';">Tidak ada jadwal perkuliahan aktif untuk hari ${namaHari} saat ini (kosong / sudah selesai semua).</td></tr>`;
        if (ruangContainer) {
            ruangContainer.innerHTML = `<p style="font-size: 13px; color: #667085; padding: 15px; font-family: 'Poppins'; font-style: italic;">Semua ruangan kosong / seluruh jadwal hari ${namaHari} telah selesai.</p>`;
        }
        return;
    }

    if (jadwalRender.length === 0) {
        tableBody.innerHTML = `<tr><td colspan="7" style="text-align: center; padding: 35px; color: #667085; font-family: 'Poppins';">Semua jadwal perkuliahan hari ini telah selesai. Klik "Lihat Semua Jadwal" untuk melihat riwayat.</td></tr>`;
    } else {
        // Jalankan render baris tabel utama secara berurutan
        jadwalRender.forEach((item) => {
            const tr = document.createElement("tr");

            // Logika Waktu Real-Time (Akan Datang / Berjalan / Selesai)
            const now = new Date();
            const currTimeStr =
                String(now.getHours()).padStart(2, "0") +
                "." +
                String(now.getMinutes()).padStart(2, "0");
            const jamParts = item.jam.split(" - ");
            const jamMulai = jamParts[0]?.trim();
            const jamSelesai = jamParts[1]?.trim();

            let statusText = "";
            let classStatus = "";

            if (currTimeStr < jamMulai) {
                statusText = "Akan Datang";
                classStatus = "info"; // Biru
            } else if (currTimeStr >= jamMulai && currTimeStr <= jamSelesai) {
                statusText = "Berjalan";
                classStatus = "success pulsing"; // Hijau Pulsing
            } else {
                statusText = "Selesai";
                classStatus = "gray-badge"; // Abu-abu
            }

            // RBAC Logika Rendering Aksi
            let aksiHTML = "";
            if (
                window.currentUserRole === "admin" ||
                window.currentUserRole === "dosen"
            ) {
                aksiHTML = `<td>
                <button class="action-btn" onclick="bukaAksiJadwal('${item.matkul}', '${item.kelas}', '${item.dosen}')">
                    <i class="fa-solid fa-ellipsis"></i>
                </button>
            </td>`;
            }

            tr.innerHTML = `
            <td>${item.jam}</td>
            <td style="font-weight: 600; color: #1d2939;">${item.matkul}</td>
            <td>${item.dosen}</td>
            <td>Ruang ${item.ruang}</td>
            <td><span class="kelas-badge">${item.kelas}</span></td>
            <td><span class="status ${classStatus}">${statusText}</span></td>
            ${aksiHTML}
        `;
            tableBody.appendChild(tr);
        });
    }

    // Jalankan render otomatis pada widget bilah kanan (Ruangan Terpakai)
    if (ruangContainer) {
        ruangContainer.innerHTML = "";

        // Filter hanya jadwal yang sedang berjalan untuk sinkronisasi Auto-Sync ruangan aktif
        const now = new Date();
        const currTimeStr =
            String(now.getHours()).padStart(2, "0") +
            "." +
            String(now.getMinutes()).padStart(2, "0");
        const ruanganTerpakaiSaatIni = jadwalHariIni.filter((item) => {
            const jamParts = item.jam.split(" - ");
            const jamMulai = jamParts[0]?.trim();
            const jamSelesai = jamParts[1]?.trim();
            return currTimeStr >= jamMulai && currTimeStr <= jamSelesai;
        });

        if (ruanganTerpakaiSaatIni.length === 0) {
            ruangContainer.innerHTML = `<p style="font-size: 13px; color: #667085; padding: 15px; font-family: 'Poppins'; font-style: italic; text-align: center;">Semua ruangan sedang kosong saat ini.</p>`;
        } else {
            const limitData = ruanganTerpakaiSaatIni.slice(0, 5); // Tampilkan maksimal 5 ruangan
            limitData.forEach((item) => {
                const div = document.createElement("div");
                div.className = "room-item";
                div.innerHTML = `
                <div class="room-left">
                    <div class="room-icon green-bg"><i class="fa-solid fa-door-open"></i></div>
                    <div class="room-text">
                        <h4>Ruang ${item.ruang}</h4>
                        <p style="white-space: nowrap; overflow: hidden; text-overflow: ellipsis; max-width: 140px;">${item.matkul}</p>
                    </div>
                </div>
                <span class="room-status green-status">Sedang Dipakai</span>
            `;
                ruangContainer.appendChild(div);
            });
        }
    }
}

